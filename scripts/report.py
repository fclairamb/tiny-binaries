#!/usr/bin/env python3
"""Collect out/<platform>/<lang>/results.tsv into results/results.json and results/RESULTS.md,
and refresh the tables in README.md between the <!-- results --> markers.

Usage: scripts/report.py
Platforms or languages that were not built are kept from the previous results/results.json.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLATFORMS = ["darwin-arm64", "linux-arm64", "linux-amd64"]
LANGS = ["c", "go", "rust", "v", "asm"]
LANG_NAMES = {"c": "C", "go": "Go", "rust": "Rust", "v": "V", "asm": "Assembly"}
PROGRAMS = ["hello", "tcp"]


def load_previous():
    try:
        with open(os.path.join(ROOT, "results", "results.json")) as f:
            return json.load(f)["sizes"]
    except (OSError, ValueError, KeyError):
        return {}


def collect():
    sizes = load_previous()  # sizes[platform][lang][binary] = {"bytes": n, "status": s}
    for p in PLATFORMS:
        for l in LANGS:
            tsv = os.path.join(ROOT, "out", p, l, "results.tsv")
            if not os.path.exists(tsv):
                continue
            rows = {}
            with open(tsv) as f:
                for line in f:
                    name, size, status, *_ = line.rstrip("\n").split("\t")
                    rows[name] = {"bytes": int(size), "status": status}
            sizes.setdefault(p, {})[l] = rows
    return sizes


def variants(lang):
    try:
        with open(os.path.join(ROOT, lang, "variants.json")) as f:
            return json.load(f)
    except OSError:
        return {}


def cell(sizes, p, l, name):
    r = sizes.get(p, {}).get(l, {}).get(name)
    if not r:
        return "-"
    if r["status"] != "PASS":
        return "fail"
    return "{:,}".format(r["bytes"])


def best(sizes, p, l, prog):
    ok = [(r["bytes"], n) for n, r in sizes.get(p, {}).get(l, {}).items()
          if n.startswith(prog + "-") and r["status"] == "PASS"]
    return min(ok) if ok else None


def tables(sizes):
    out = []
    head = "| | " + " | ".join(PLATFORMS) + " |\n|---|" + "---:|" * len(PLATFORMS)
    out.append("### Smallest passing binary per language (bytes)\n")
    for prog in PROGRAMS:
        out.append("**%s**\n\n%s" % (prog, head.replace("| |", "| Language |", 1)))
        for l in LANGS:
            cells = []
            for p in PLATFORMS:
                b = best(sizes, p, l, prog)
                cells.append("{:,} (`{}`)".format(b[0], b[1].split("-", 1)[1]) if b else "-")
            out.append("| %s | %s |" % (LANG_NAMES[l], " | ".join(cells)))
        out.append("")
    out.append("### All variants (bytes)\n")
    for prog in PROGRAMS:
        out.append("**%s**\n\n%s" % (prog, head.replace("| |", "| Language | Variant |", 1)
                                       .replace("|---|", "|---|---|", 1)))
        for l in LANGS:
            names = list(variants(l))
            for p in PLATFORMS:
                for n in sizes.get(p, {}).get(l, {}):
                    v = n.split("-", 1)[1]
                    if n.startswith(prog + "-") and v not in names:
                        names.append(v)
            for v in names:
                name = "%s-%s" % (prog, v)
                cells = [cell(sizes, p, l, name) for p in PLATFORMS]
                if any(c != "-" for c in cells):
                    out.append("| %s | `%s` | %s |" % (LANG_NAMES[l], v, " | ".join(cells)))
        out.append("")
    out.append("### Variants\n")
    for l in LANGS:
        vs = variants(l)
        if vs:
            out.append("**%s**\n" % LANG_NAMES[l])
            out += ["- `%s`: %s" % (v, d) for v, d in vs.items()]
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    sizes = collect()
    os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)
    with open(os.path.join(ROOT, "results", "results.json"), "w") as f:
        json.dump({"sizes": sizes}, f, indent=1, sort_keys=True)
        f.write("\n")
    md = tables(sizes)
    with open(os.path.join(ROOT, "results", "RESULTS.md"), "w") as f:
        f.write("# Results\n\nGenerated by `scripts/report.py`.\n\n" + md)
    readme = os.path.join(ROOT, "README.md")
    if os.path.exists(readme):
        s = open(readme).read()
        s2 = re.sub(r"(<!-- results:start -->\n).*?(<!-- results:end -->)",
                    lambda m: m.group(1) + md + m.group(2), s, flags=re.S)
        if s2 != s:
            open(readme, "w").write(s2)
    print(md)


if __name__ == "__main__":
    main()
